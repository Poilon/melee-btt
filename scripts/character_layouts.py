"""Separate, authored topologies. Rectangles are (left, top, width, depth).

Marks refer to a surface, horizontal fraction and target clearance. Multiple
marks can share a room/floor; their count does not determine the terrain.
"""

def layout(surfaces,marks,bounds=None):
    targets=[(surfaces[i][0]+surfaces[i][2]*f,surfaces[i][1]+h) for i,f,h in marks]
    l=min(s[0] for s in surfaces)-35;r=max(s[0]+s[2] for s in surfaces)+35
    top=max(s[1] for s in surfaces)+65
    return {'surfaces':surfaces,'targets':targets,'spawn':(surfaces[0][0]+20,surfaces[0][1]+2),
            'bounds':bounds or (l,top,r,-35)}


